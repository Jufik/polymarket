@app.cell
def overall_summary(mo, valid, pl):
    """Aggregate performance by each parameter dimension."""

    by_lb = valid.group_by("lookback").agg(
        pl.col("oos_positions").sum().alias("total_pos"),
        pl.col("oos_wins").sum().alias("total_wins"),
        pl.col("oos_total_pnl").sum().alias("total_pnl"),
        pl.col("n_traders").mean().alias("avg_traders"),
    ).with_columns(
        (pl.col("total_wins") / pl.col("total_pos")).alias("oos_hr"),
        (pl.col("total_pnl") / pl.col("total_pos")).alias("pnl_per_pos"),
    ).sort("lookback")

    by_hr = valid.group_by("min_hr").agg(
        pl.col("oos_positions").sum().alias("total_pos"),
        pl.col("oos_wins").sum().alias("total_wins"),
        pl.col("oos_total_pnl").sum().alias("total_pnl"),
        pl.col("n_traders").mean().alias("avg_traders"),
    ).with_columns(
        (pl.col("total_wins") / pl.col("total_pos")).alias("oos_hr"),
        (pl.col("total_pnl") / pl.col("total_pos")).alias("pnl_per_pos"),
    ).sort("min_hr")

    by_pos = valid.group_by("min_pos").agg(
        pl.col("oos_positions").sum().alias("total_pos"),
        pl.col("oos_wins").sum().alias("total_wins"),
        pl.col("oos_total_pnl").sum().alias("total_pnl"),
        pl.col("n_traders").mean().alias("avg_traders"),
    ).with_columns(
        (pl.col("total_wins") / pl.col("total_pos")).alias("oos_hr"),
        (pl.col("total_pnl") / pl.col("total_pos")).alias("pnl_per_pos"),
    ).sort("min_pos")

    def _fmt_table(title: str, data: pl.DataFrame, key_col: str) -> str:
        rows = []
        rows.append(f"### {title}")
        rows.append(f"| {key_col} | Avg Traders | OOS Positions | OOS HR | PnL/Pos | Total PnL |")
        rows.append("|---:|---:|---:|---:|---:|---:|")
        for r in data.iter_rows(named=True):
            rows.append(
                f"| {r[key_col]} | {r['avg_traders']:,.0f} | {r['total_pos']:,} | "
                f"{r['oos_hr']:.4f} | ${r['pnl_per_pos']:.2f} | ${r['total_pnl']:,.0f} |"
            )
        return "\n".join(rows)

    mo.md(
        f"""
    ## Marginal Parameter Effects

    Each dimension aggregated across all values of other parameters.

    {_fmt_table("By Lookback Window (months)", by_lb, "lookback")}

    **Finding**: Longer lookbacks yield modestly higher PnL/position ($2.84 at 3mo vs $5.05 at 12mo).
    OOS hit rate is nearly identical (~56.9%) across all lookback windows.
    Longer lookbacks provide larger trader pools (more signal, more stability).

    {_fmt_table("By Min Hit Rate Threshold", by_hr, "min_hr")}

    **Finding**: Non-monotonic PnL pattern! Negative PnL at 0.60-0.70 thresholds, then strongly
    positive at 0.75-0.80. This is driven by low min_pos settings letting noise traders through
    (see heatmap below). At min_pos >= 20, the relationship becomes monotonically positive.

    {_fmt_table("By Min Positions", by_pos, "min_pos")}

    **Critical finding**: min_pos=5 is **poisonous** (-$9.72/pos). This is classic overfitting --
    a trader with 5 positions and 4 wins (80% HR) is indistinguishable from luck.
    min_pos >= 20 is required for the signal to be exploitable.
    """
    )
    return by_lb, by_hr, by_pos


@app.cell
def heatmap_pnl(mo, valid, pl):
    """Heatmap: min_hr x min_pos -> PnL/position."""
    import plotly.graph_objects as go
    import numpy as np

    cross = valid.group_by(["min_hr", "min_pos"]).agg(
        pl.col("oos_positions").sum().alias("total_pos"),
        pl.col("oos_total_pnl").sum().alias("total_pnl"),
    ).with_columns(
        (pl.col("total_pnl") / pl.col("total_pos")).alias("pnl_per_pos"),
    ).sort(["min_hr", "min_pos"])

    hr_vals = sorted(cross["min_hr"].unique().to_list())
    pos_vals = sorted(cross["min_pos"].unique().to_list())

    z = []
    for mp in pos_vals:
        row = []
        for mh in hr_vals:
            val = cross.filter(
                (pl.col("min_hr") == mh) & (pl.col("min_pos") == mp)
            )["pnl_per_pos"]
            row.append(float(val[0]) if len(val) > 0 else 0)
        z.append(row)

    fig = go.Figure(data=go.Heatmap(
        z=z,
        x=[f"{h:.2f}" for h in hr_vals],
        y=[str(p) for p in pos_vals],
        colorscale="RdYlGn",
        zmid=0,
        text=[[f"${v:.1f}" for v in row] for row in z],
        texttemplate="%{text}",
        textfont={"size": 14},
        colorbar=dict(title="PnL/Pos ($)"),
    ))
    fig.update_layout(
        title="OOS PnL per Position: min_hit_rate x min_positions<br>"
              "<sub>Aggregated across all lookback windows and test months</sub>",
        xaxis_title="Min Hit Rate Threshold",
        yaxis_title="Min Positions in Training",
        height=400,
        width=800,
    )

    mo.md(
        f"""
    ## Heatmap: PnL/Position by HR Threshold x Min Positions

    {mo.as_html(fig)}

    **Key takeaway**: The profitable regime is in the **bottom-right corner** --
    high HR threshold (>= 0.75) combined with strict position minimum (>= 20).

    - min_pos=5 is negative across all HR thresholds (overfitting)
    - At min_pos >= 20, PnL/pos increases monotonically with HR threshold
    - Best cell: min_hr=0.80, min_pos=20 -> $65.70/position
    - The "sweet spot" balancing edge vs volume: min_hr=0.75, min_pos=20 -> $34.99/pos
    """
    )
    return cross,


